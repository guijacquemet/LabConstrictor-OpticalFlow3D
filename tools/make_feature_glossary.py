"""Write docs/features.md, the glossary of every feature column, from the feature dictionary.

The definitions live in ``src/opticalflow3d_profiler/feature_dictionary.py`` (the same
dictionary every run writes to ``features/feature_dictionary.json``). To change a definition,
edit that module and run ``python tools/make_feature_glossary.py``; never edit the page by
hand. ``tests/profiler/test_feature_glossary.py`` fails when the page is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from opticalflow3d_profiler.feature_dictionary import (  # noqa: E402
    AXIAL,
    BIOLOGICAL,
    ORIENTATION,
    QC,
    FeatureDef,
    frame_dictionary,
)

PAGE = ROOT / "docs" / "features.md"

FAMILIES = {
    "magnitude": (
        "Speed",
        "How fast the intensity patterns move. One family is computed per run: `speed_xy_*` "
        "with XY speed (the default) or `speed_3d_*` with 3D speed (`speed_mode = xyz`, "
        "experimental because the axial component is less reliable in shallow stacks).",
    ),
    "components": (
        "Velocity components",
        "The X, Y and Z components of the velocity separately. Every X and Y statistic "
        "(signed mean, spread and absolute mean) depends on how the image axes lie on the "
        "sample, so they are orientation descriptors; Z is defined by the microscope.",
    ),
    "collective": (
        "Collective motion and direction",
        "Whether neighbouring and distant nuclei move together, and how directions are "
        "spread. Global coherence and the angular features do not depend on image "
        "orientation (the angular entropy within its measured numerical error); local "
        "coherence uses a square window on the image grid. The angular features use only "
        "vectors whose XY speed exceeds "
        "`min_direction_speed`, and need at least `min_direction_vectors` of them.",
    ),
    "spatial": (
        "Spatial heterogeneity",
        "How different the motion is between regions of the field of view: the image is cut "
        "into square regions of `region_size_px` pixels and each full region with at least "
        "`min_region_voxels` analysed voxels gets its own speed and coherence. The grid is "
        "fixed to the image axes, so these values depend on how the sample lies in the image.",
    ),
    "quality": (
        "Quality control",
        "Metadata that qualify a measurement (reliability, coverage, object sizes, brightness "
        "change). They are never given to MorphoCoverage as features; use them to check that "
        "conditions are comparable.",
    ),
}
USE = {
    BIOLOGICAL: "readout",
    AXIAL: "axial readout (experimental)",
    ORIENTATION: "orientation descriptor",
    QC: "quality control",
}
UNIT = {"lateral": "speed unit", "axial": "axial speed unit", "1": "none (ratio)"}


def cell(text: str) -> str:
    """Return text safe for one Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def definitions() -> list[FeatureDef]:
    """Return every per-frame definition: XY and 3D speed families, intensity included."""
    xyz = frame_dictionary("xyz", intensity=True)
    xy_only = [d for d in frame_dictionary("xy") if d.family == "magnitude"]
    return xy_only + xyz


def table(rows: list[FeatureDef]) -> list[str]:
    """Return the Markdown table of a family."""
    lines = [
        "| Column | What it measures | How it is computed | Unit | Use | Undefined (empty) when |",
        "|---|---|---|---|---|---|",
    ]
    for d in rows:
        lines.append(
            f"| `{d.name}` | {cell(d.description)} | `{cell(d.formula)}` | "
            f"{UNIT.get(d.unit, d.unit)} | {USE[d.applicability]} | {cell(d.undefined)} |"
        )
    return lines


def glossary_markdown() -> str:
    """Return the full glossary page."""
    rows = definitions()
    out = [
        "# Feature glossary",
        "",
        "[:arrow_left: Documentation index](index.md)",
        "",
        "<!-- Generated by tools/make_feature_glossary.py from feature_dictionary.py; "
        "do not edit by hand. -->",
        "",
        "Every column of the feature tables, what it measures, how it is computed and when it "
        "is left empty. The same definitions are written into every run as "
        "`features/feature_dictionary.json`. For the method behind them see "
        "[How it works](theory.md); for interpretation see "
        "[Interpreting results](results.md#interpreting-results).",
        "",
        "## How to read the tables",
        "",
        "- **Column names.** In the feature tables, every feature column carries the name of "
        "the analysed object set: `Nuclei__speed_xy_median` with a foreground (the name is "
        "yours to choose), `whole__speed_xy_median` without one (MorphoBricks naming). "
        "Quality-control columns (`qc_*`) have no prefix. The tables below give the column "
        "without its prefix.",
        "- **Per frame and per field of view.** `features_per_frame.csv` holds one row per "
        "analysed time point `t` of every field of view. `features_per_fov.csv` holds one row "
        "per field of view with the **same column names**: each value is the mean over that "
        "field of view's time points (the circular mean for directions in degrees), with "
        "undefined time points left out, never counted as 0. The field of view is the "
        "observation unit of the statistics.",
        "- **Units.** *speed unit* is µm/min when the pixel size and frame interval are "
        "confirmed, otherwise pixel/frame; *axial speed unit* is µm/min with a confirmed "
        "Z spacing and frame interval, otherwise slice/frame. The unit of a run is written in "
        "`feature_dictionary.json` (`units`).",
        "- **Use.** *readout*: given to MorphoCoverage. *axial readout (experimental)*: "
        "given to MorphoCoverage only when you include axial features. *orientation "
        "descriptor*: depends on how the image is oriented, never a readout. *quality "
        "control*: metadata, never a readout.",
        "- **Undefined.** An empty cell is a value that does not exist (for example a "
        "coefficient of variation when the mean speed is 0). The reason is recorded per row in "
        "`undefined_features` of `features_per_frame.csv`. Undefined values are never set "
        "to 0.",
        "- **Speeds.** Optical-flow speeds are the motion of intensity patterns, with a "
        "size-dependent gain bias documented in [Validation](validation.md); they are not "
        "tracked nuclear displacements.",
        "",
    ]
    for family, (title, intro) in FAMILIES.items():
        members = [d for d in rows if d.family == family]
        out += [f"## {title}", "", intro, "", *table(members), ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    """Write the page."""
    PAGE.write_text(glossary_markdown(), encoding="utf-8")
    print(f"Wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
